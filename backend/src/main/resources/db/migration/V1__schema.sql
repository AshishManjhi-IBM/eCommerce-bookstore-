-- E-Bookstore schema. Works on PostgreSQL and H2 (PostgreSQL mode, used by tests).

CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name     VARCHAR(100) NOT NULL,
    last_name      VARCHAR(100) NOT NULL,
    email          VARCHAR(255) NOT NULL UNIQUE,
    password_hash  VARCHAR(100) NOT NULL,
    role           VARCHAR(20)  NOT NULL,
    gift_points    INT          NOT NULL DEFAULT 0,
    wallet_balance NUMERIC(12,2) NOT NULL DEFAULT 0,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE addresses (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT NOT NULL REFERENCES users(id),
    first_name         VARCHAR(100) NOT NULL,
    last_name          VARCHAR(100) NOT NULL,
    address_line       VARCHAR(255) NOT NULL,
    email              VARCHAR(255) NOT NULL,
    phone_country_code VARCHAR(10)  NOT NULL,
    phone              VARCHAR(20)  NOT NULL,
    city               VARCHAR(100) NOT NULL,
    pin                VARCHAR(12)  NOT NULL,
    state              VARCHAR(100) NOT NULL,
    country            VARCHAR(100) NOT NULL,
    default_address    BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_addresses_user ON addresses(user_id);

CREATE TABLE stores (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   VARCHAR(200) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE store_policies (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id    BIGINT NOT NULL REFERENCES stores(id),
    title       VARCHAR(200) NOT NULL,
    description VARCHAR(2000) NOT NULL
);

CREATE TABLE catalogs (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id BIGINT NOT NULL REFERENCES stores(id),
    name     VARCHAR(200) NOT NULL,
    active   BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE categories (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE brands (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL UNIQUE
);

CREATE TABLE writers (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    bio  VARCHAR(2000)
);

CREATE TABLE products (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title             VARCHAR(255) NOT NULL,
    description       VARCHAR(1000),
    back_cover_blurb  VARCHAR(4000),
    isbn              VARCHAR(20) UNIQUE,
    language          VARCHAR(50) NOT NULL,
    book_format       VARCHAR(20) NOT NULL,
    price             NUMERIC(10,2) NOT NULL,
    stock             INT NOT NULL DEFAULT 0,
    delivery_days     INT,
    cover_url         VARCHAR(500),
    genre_tags        VARCHAR(255),
    active            BOOLEAN NOT NULL DEFAULT TRUE,
    copies_sold       INT NOT NULL DEFAULT 0,
    rating_avg        NUMERIC(3,2) NOT NULL DEFAULT 0,
    rating_count      INT NOT NULL DEFAULT 0,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    category_id       BIGINT NOT NULL REFERENCES categories(id),
    brand_id          BIGINT NOT NULL REFERENCES brands(id),
    writer_id         BIGINT NOT NULL REFERENCES writers(id),
    catalog_id        BIGINT REFERENCES catalogs(id)
);
CREATE INDEX idx_products_category ON products(category_id);
CREATE INDEX idx_products_brand ON products(brand_id);
CREATE INDEX idx_products_writer ON products(writer_id);

CREATE TABLE reviews (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT NOT NULL REFERENCES products(id),
    user_id     BIGINT NOT NULL REFERENCES users(id),
    user_name   VARCHAR(200) NOT NULL,
    rating      INT NOT NULL,
    review_text VARCHAR(100),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_review UNIQUE (product_id, user_id)
);

CREATE TABLE wishlist_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id),
    product_id BIGINT NOT NULL REFERENCES products(id),
    CONSTRAINT uq_wishlist UNIQUE (user_id, product_id)
);

CREATE TABLE baskets (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT UNIQUE REFERENCES users(id),
    guest_token VARCHAR(64) UNIQUE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE basket_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    basket_id  BIGINT NOT NULL REFERENCES baskets(id),
    product_id BIGINT NOT NULL REFERENCES products(id),
    quantity   INT NOT NULL,
    CONSTRAINT uq_basket_item UNIQUE (basket_id, product_id)
);

CREATE TABLE coupons (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(50) NOT NULL UNIQUE,
    percent_off INT NOT NULL,
    active      BOOLEAN NOT NULL DEFAULT TRUE,
    expires_at  TIMESTAMP WITH TIME ZONE
);

CREATE TABLE orders (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               BIGINT NOT NULL REFERENCES users(id),
    status                VARCHAR(30) NOT NULL,
    subtotal              NUMERIC(12,2) NOT NULL,
    discount              NUMERIC(12,2) NOT NULL,
    tax                   NUMERIC(12,2) NOT NULL,
    delivery_charge       NUMERIC(12,2) NOT NULL,
    gift_points_redeemed  INT NOT NULL DEFAULT 0,
    gift_points_discount  NUMERIC(12,2) NOT NULL DEFAULT 0,
    gift_points_earned    INT NOT NULL DEFAULT 0,
    total_amount          NUMERIC(12,2) NOT NULL,
    coupon_code           VARCHAR(50),
    first_name            VARCHAR(100) NOT NULL,
    last_name             VARCHAR(100) NOT NULL,
    address_line          VARCHAR(255) NOT NULL,
    email                 VARCHAR(255) NOT NULL,
    phone_country_code    VARCHAR(10)  NOT NULL,
    phone                 VARCHAR(20)  NOT NULL,
    city                  VARCHAR(100) NOT NULL,
    pin                   VARCHAR(12)  NOT NULL,
    state                 VARCHAR(100) NOT NULL,
    country               VARCHAR(100) NOT NULL,
    estimated_delivery    DATE,
    placed_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    cancellable_until     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_orders_user ON orders(user_id);

CREATE TABLE order_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT NOT NULL REFERENCES orders(id),
    product_id    BIGINT NOT NULL REFERENCES products(id),
    title         VARCHAR(255) NOT NULL,
    quantity      INT NOT NULL,
    unit_price    NUMERIC(10,2) NOT NULL,
    delivery_date DATE
);
CREATE INDEX idx_order_items_order ON order_items(order_id);

CREATE TABLE payments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT NOT NULL UNIQUE REFERENCES orders(id),
    method          VARCHAR(20) NOT NULL,
    status          VARCHAR(20) NOT NULL,
    amount          NUMERIC(12,2) NOT NULL,
    card_last4      VARCHAR(4),
    transaction_ref VARCHAR(64) NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    refunded_at     TIMESTAMP WITH TIME ZONE
);

CREATE TABLE shipping_rates (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region        VARCHAR(100) NOT NULL UNIQUE,
    charge        NUMERIC(10,2) NOT NULL,
    delivery_days INT NOT NULL
);
